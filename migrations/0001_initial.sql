CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY NOT NULL,
  username TEXT NOT NULL UNIQUE,
  password TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS clips (
  id TEXT PRIMARY KEY NOT NULL,
  title TEXT NOT NULL,
  content TEXT NOT NULL DEFAULT '',
  category TEXT NOT NULL DEFAULT 'clipboard',
  pinned INTEGER NOT NULL DEFAULT 0,
  starred INTEGER NOT NULL DEFAULT 0,
  deleted INTEGER NOT NULL DEFAULT 0,
  is_structured INTEGER NOT NULL DEFAULT 0,
  fields TEXT NOT NULL DEFAULT '[]',
  tags TEXT NOT NULL DEFAULT '[]',
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS tags (id TEXT PRIMARY KEY NOT NULL, name TEXT NOT NULL UNIQUE, color TEXT NOT NULL DEFAULT '#888888');
CREATE TABLE IF NOT EXISTS bookmarks (id TEXT PRIMARY KEY NOT NULL, title TEXT NOT NULL, url TEXT NOT NULL, description TEXT NOT NULL DEFAULT '', domain TEXT NOT NULL DEFAULT '', category TEXT NOT NULL DEFAULT 'general', bookmark_tags TEXT NOT NULL DEFAULT '[]', favicon TEXT, created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS prompts (id TEXT PRIMARY KEY NOT NULL, name TEXT NOT NULL, short_desc TEXT NOT NULL DEFAULT '', template TEXT NOT NULL DEFAULT '', category TEXT NOT NULL DEFAULT 'custom', color TEXT NOT NULL DEFAULT '#f59e0b', shortcut TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS uploads (id TEXT PRIMARY KEY NOT NULL, filename TEXT NOT NULL, content TEXT NOT NULL DEFAULT '', mime_type TEXT NOT NULL DEFAULT 'text/plain', size INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL);

CREATE INDEX IF NOT EXISTS clips_updated_at_idx ON clips(updated_at DESC);
CREATE INDEX IF NOT EXISTS bookmarks_created_at_idx ON bookmarks(created_at DESC);
